#!/bin/sh
set -e

# nginx master 以 root 运行,但 cap_drop:ALL 去掉了 DAC_OVERRIDE。nginx 在
# reopen(logrotate 的 USR1)时会把日志文件 chown 给 worker 用户(uid 101),
# 以便 worker 写入;于是稳定态下 /var/log/nginx/*.log 归 101 所有。下次冷启动
# 时 root master 需要先 open() 这些已存在的文件,但无 DAC_OVERRIDE 无法打开
# 101 属主的文件 → [emerg] 退出,nginx 起不来(容器重建即触发)。这里在启动前
# 把日志重置为 root 属主:master 即可 open()(随后照常 chown 给 worker 供写入)。
chown -R root:root /var/log/nginx 2>/dev/null || true

# 预创建 fail2ban jail 的 logpath:supervisord 对 nginx/fail2ban 无启动顺序
# 保证,冷启动时 fail2ban 若先于 nginx 创建该文件会启动失败进入重启循环
# (supervisord priority 只能整体排序,预创建是两种程序名都成立的最小修法)。
touch /var/log/nginx/admin-access.log

# Fetch latest Cloudflare IP ranges on every container start
fetch-cloudflare-ips.sh 2>/dev/null || echo "WARNING: failed to fetch Cloudflare IP ranges, using cached" >&2

# Set up logrotate (hourly) + Cloudflare IP range refresh (daily 04:17).
# CF IP 刷新只启动时跑一次会长期漂移:新增网段后 real_ip 不再改写,fail2ban
# 会误封 CF 边缘 IP。刷新脚本自带变化检测(内容不变不 reload)。
# 注意 crontab - 为整体替换,两行必须一次写入。
{ echo "0 * * * * /usr/sbin/logrotate /etc/logrotate.d/nginx"
  echo "17 4 * * * /usr/local/bin/refresh-cloudflare-ips.sh"
} | crontab -

# Auth files are generated by admin before nginx starts. If the auth directory
# is writable (e.g. local manual runs), keep the files present for nginx.
if [ -w /etc/nginx/htpasswd ]; then
    if [ -d /etc/nginx/htpasswd/.htpasswd-proxy ]; then
        rm -rf /etc/nginx/htpasswd/.htpasswd-proxy || true
    fi
    touch /etc/nginx/htpasswd/.htpasswd /etc/nginx/htpasswd/.htpasswd-proxy 2>/dev/null || true
fi

exec "$@"
