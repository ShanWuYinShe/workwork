package auth

import (
	"admin/internal/platform"
	"context"
	"fmt"
	"log"
	"net"
	"strings"
	"sync"
	"time"

	"github.com/docker/docker/client"
)

// blocklistSync 把封禁列表写入 nginx map 配置并去抖 reload。路径与
// ipBlockStore 都由 Security 构造注入，不再有包级路径/客户端全局。
type blocklistSync struct {
	path    string
	blocker *ipBlockStore

	mu      sync.Mutex
	cli     *client.Client
	timer   *time.Timer
	running bool
	pending bool
}

func newBlocklistSync(path string, blocker *ipBlockStore) *blocklistSync {
	return &blocklistSync{path: path, blocker: blocker}
}

// schedule 在封禁列表变更后调度一次 nginx 同步(去抖 2s)。
// 调用方可能持 blocker.mu，这里只做调度，实际写入/reload 在 timer goroutine。
func (b *blocklistSync) schedule() {
	b.mu.Lock()
	defer b.mu.Unlock()
	if b.timer != nil {
		return
	}
	if b.running {
		b.pending = true
		return
	}
	b.timer = time.AfterFunc(2*time.Second, func() {
		b.mu.Lock()
		b.timer = nil
		b.running = true
		cli := b.cli
		b.mu.Unlock()
		for cli != nil {
			if err := b.sync(cli); err != nil {
				log.Printf("WARNING: sync blocked IPs to nginx: %v", err)
			}
			b.mu.Lock()
			if !b.pending {
				b.running = false
				b.mu.Unlock()
				return
			}
			b.pending = false
			b.mu.Unlock()
		}
		b.mu.Lock()
		b.running = false
		b.mu.Unlock()
	})
}

func (b *blocklistSync) sync(cli *client.Client) error {
	if err := b.write(); err != nil {
		return err
	}
	return reloadNginx(cli)
}

// write 只写封禁 map 配置、不触发 reload。启动引导同步调用它：nginx
// server 块引用 blocked-ips.conf 定义的变量，该文件缺失时 nginx -t 直接
// emerg（undefined variable）。
func (b *blocklistSync) write() error {
	entries := b.blocker.list()
	var sb strings.Builder
	sb.WriteString("# generated by admin ipBlocker — do not edit\n")
	sb.WriteString("map $http_cf_connecting_ip $workwork_blocked_cf {\n")
	sb.WriteString("    default 0;\n")
	for _, e := range entries {
		if validBlockIP(e.IP) && !blockEntryExpired(e) {
			sb.WriteString("    " + e.IP + " 1;\n")
		}
	}
	sb.WriteString("}\n")
	sb.WriteString("map $remote_addr $workwork_blocked_direct {\n")
	sb.WriteString("    default 0;\n")
	for _, e := range entries {
		if validBlockIP(e.IP) && !blockEntryExpired(e) {
			sb.WriteString("    " + e.IP + " 1;\n")
		}
	}
	sb.WriteString("}\n")
	if err := platform.AtomicWriteFile(b.path, []byte(sb.String()), 0644); err != nil {
		return fmt.Errorf("write %s: %w", b.path, err)
	}
	return nil
}

func (b *blocklistSync) setClient(cli *client.Client) {
	b.mu.Lock()
	defer b.mu.Unlock()
	b.cli = cli
}

// validBlockIP 校验条目 IP 是合法 IP 再写入 nginx map。
func validBlockIP(raw string) bool {
	ip := net.ParseIP(strings.TrimSpace(raw))
	return ip != nil && raw == strings.TrimSpace(raw)
}

// blockEntryExpired 判断封禁条目是否已过期（空 ExpiresAt = 永久）。
func blockEntryExpired(e ipBlockEntry) bool {
	if e.ExpiresAt == "" {
		return false
	}
	t, err := time.Parse(time.RFC3339, e.ExpiresAt)
	return err == nil && time.Now().UTC().After(t)
}

// reloadNginx 平滑重载 nginx 配置（新配置校验失败时 nginx 保留旧配置）。
func reloadNginx(cli *client.Client) error {
	ctx, cancel := context.WithTimeout(context.Background(), 15*time.Second)
	defer cancel()
	id, err := platform.FindContainer(ctx, cli, "nginx")
	if err != nil {
		return fmt.Errorf("find nginx container: %w", err)
	}
	return platform.ContainerExec(ctx, cli, id, "nginx", "-s", "reload")
}
