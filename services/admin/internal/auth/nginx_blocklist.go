// nginxBlockedConfPath 是 nginx 容器 conf.d 挂载目录内的封禁配置文件
// (宿主机 .wework/generated/nginx/ ↔ admin 容器 /app/data/generated/nginx/ ↔
// nginx 容器 /etc/nginx/conf.d)。nginx.conf.tmpl 的 server 块引用其中定义的
// map 变量,因此封禁对 nginx 代理的全部 location 生效(XHTTP /proxy/query、
// 媒体 API、admin SPA),不再只作用于 admin 应用层。
const nginxBlockedConfPath = "/app/data/generated/nginx/blocked-ips.conf"

// blocklistSyncCli 由 main 注入的 docker client,用于触发 nginx reload。
var blocklistSyncCli *client.Client

// nginx 封禁同步的节流状态:封禁列表变更后最多每 2s 合并一次写入 + reload。
var (
	blocklistSyncMu      sync.Mutex
	blocklistSyncTimer   *time.Timer
	blocklistSyncRunning bool // 一轮 sync 正在执行(timer 已到期、回调未返回)
	blocklistSyncPending bool // sync 执行期间又有新变更,需合并重跑一轮
)

// ScheduleBlocklistSync 在封禁列表变更后调度一次 nginx 同步(去抖):
// 连续变更(如批量封禁/解封)在窗口内只生成一次配置、reload 一次。
// 注意:调用方可能持锁(ipBlocker.save 持 ipBlocker.mu),这里只做调度,
// 实际生成与 reload 在独立 timer goroutine 中执行,不阻塞请求热路径。
func ScheduleBlocklistSync() {
	blocklistSyncMu.Lock()
	defer blocklistSyncMu.Unlock()
	if blocklistSyncTimer != nil {
		return
	}
	if blocklistSyncRunning {
		// 上一轮 sync 仍在执行:只标记 pending,由其回调尾部合并重跑。
		// 不另起 timer——旧回调开头已把 timer 置 nil,新 timer 会与仍在
		// 执行的 sync 并发重叠,产生冗余写配置 + 冗余 nginx reload。
		blocklistSyncPending = true
		return
	}
	blocklistSyncTimer = time.AfterFunc(2*time.Second, func() {
		blocklistSyncMu.Lock()
		blocklistSyncTimer = nil
		blocklistSyncRunning = true
		cli := blocklistSyncCli
		blocklistSyncMu.Unlock()
		for cli != nil {
			if err := syncBlockedIPsToNginx(cli); err != nil {
				log.Printf("WARNING: sync blocked IPs to nginx: %v", err)
			}
			// 退出与清 running 必须在同一临界区:若先 unlock 再清,
			// 新变更会看到 running==true 只置 pending,而本回调已返回,
			// pending 无人消费,该变更直到下次任意封禁变更才会同步。
			blocklistSyncMu.Lock()
			if !blocklistSyncPending {
				blocklistSyncRunning = false
				blocklistSyncMu.Unlock()
				return
			}
			blocklistSyncPending = false
			blocklistSyncMu.Unlock()
			// 立即重跑而非再等 2s:pending 表示重跑期间有真实变更,
			// 重跑读的是最新快照,天然合并窗口内的全部变更。
		}
		// cli == nil(docker client 尚未注入):放弃本次,等下次变更重新调度。
		blocklistSyncMu.Lock()
		blocklistSyncRunning = false
		blocklistSyncMu.Unlock()
	})
}

// syncBlockedIPsToNginx 把当前未过期封禁列表写成 nginx map 配置并 reload:
//   - $workwork_blocked_cf:按 CF-Connecting-IP 匹配(走 Cloudflare 时的真实客户端 IP,
//     此时 $remote_addr 是 CF 边缘 IP,deny 会误伤整片用户);
//   - $workwork_blocked_direct:按 $remote_addr 匹配(直连场景)。
//
// 模板 server 块对两个变量做 `if (...) return 403`,封禁因此覆盖全部 location。
// reload 失败(如 nginx 正在重启)只记日志:nginx 保留旧配置,不会因此中断服务。
func syncBlockedIPsToNginx(cli *client.Client) error {
	if err := WriteBlockedIPsConf(); err != nil {
		return err
	}
	return reloadNginx(cli)
}

// WriteBlockedIPsConf 只写封禁 map 配置、不触发 reload。启动引导
// (generateConfigs)同步调用它:nginx.conf.tmpl 的 server 块直接引用
// blocked-ips.conf 定义的变量,该文件缺失时 nginx -t 直接 emerg
// (undefined variable,并非注释里说的"空串");若只靠 ScheduleBlocklistSync
// 的 2s 去抖异步写,冷启动窗口内 nginx 会崩溃重启数轮才自愈。
func WriteBlockedIPsConf() error {
	entries := ipBlocker.list()
	var sb strings.Builder
	sb.WriteString("# generated by admin ipBlocker — do not edit\n")
	sb.WriteString("map $http_cf_connecting_ip $workwork_blocked_cf {\n")
	sb.WriteString("    default 0;\n")
	for _, e := range entries {
		if validBlockIP(e.IP) && !blockEntryExpired(e) {
			sb.WriteString("    " + e.IP + " 1;\n")
		}
	}
	sb.WriteString("}\n")
	sb.WriteString("map $remote_addr $workwork_blocked_direct {\n")
	sb.WriteString("    default 0;\n")
	for _, e := range entries {
		if validBlockIP(e.IP) && !blockEntryExpired(e) {
			sb.WriteString("    " + e.IP + " 1;\n")
		}
	}
	sb.WriteString("}\n")
	if err := platform.AtomicWriteFile(nginxBlockedConfPath, []byte(sb.String()), 0644); err != nil {
		return fmt.Errorf("write %s: %w", nginxBlockedConfPath, err)
	}
	return nil
}

// validBlockIP 校验条目 IP 是合法 IP 再写入 nginx map。内存路径的条目都经过
// ParseIP/客户端 IP 解析,但 load() 从磁盘恢复的 blocked-ips.json 未校验——
// 文件被篡改时可借 map 配置向 nginx 注入任意指令,这里以 net.ParseIP 兜底。
func validBlockIP(raw string) bool {
	ip := net.ParseIP(strings.TrimSpace(raw))
	return ip != nil && raw == strings.TrimSpace(raw)
}

// blockEntryExpired 判断封禁条目是否已过期(ExpiresAt 为空 = 永久封禁)。
func blockEntryExpired(e ipBlockEntry) bool {
	if e.ExpiresAt == "" {
		return false
	}
	t, err := time.Parse(time.RFC3339, e.ExpiresAt)
	return err == nil && time.Now().UTC().After(t)
}

// reloadNginx 平滑重载 nginx 配置(新配置校验失败时 nginx 保留旧配置)。
func reloadNginx(cli *client.Client) error {
	ctx, cancel := context.WithTimeout(context.Background(), 15*time.Second)
	defer cancel()
	id, err := platform.FindContainer(ctx, cli, "nginx")
	if err != nil {
		return fmt.Errorf("find nginx container: %w", err)
	}
	return platform.ContainerExec(ctx, cli, id, "nginx", "-s", "reload")
}

// SetBlocklistClient 由 main 装配注入 docker client。
func SetBlocklistClient(cli *client.Client) { blocklistSyncCli = cli }
